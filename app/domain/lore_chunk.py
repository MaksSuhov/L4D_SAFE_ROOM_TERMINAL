"""Доменная сущность фрагмента лора.

Сущность описывает запись архива так, как её видит конвейер выборки: текст, его
происхождение и уровень доверия. Эмбеддинга здесь нет намеренно — вектор
принадлежит хранилищу, а не домену, и ни один сервис не вправе его читать.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(slots=True)
class LoreChunk:
    """Один извлекаемый фрагмент лора Left 4 Dead.

    Помимо текста запись несёт своё происхождение — откуда она взялась и насколько
    ей можно доверять, — потому что конвейер выборки отвечает по-разному в
    зависимости от :attr:`source_type`.
    """

    content: str
    content_hash: str
    """Хеш текста: тождество записи в архиве, по нему же слияние выборки отличает
    одну запись от другой."""
    source_type: str
    topic: str
    title: str
    id: int | None = None
    character_name: str | None = None
    source_url: str = ""
